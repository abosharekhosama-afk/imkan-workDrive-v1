  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  KEY `office_operations_org_id_file_id_revision_idx` (`org_id`,`file_id`,`revision`),
