CREATE TABLE `office_presence` (
  `id` CHAR(36) NOT NULL,
  `org_id` CHAR(36) NOT NULL,
  `file_id` CHAR(36) NOT NULL,
  `session_id` CHAR(36) NOT NULL,
  `user_id` CHAR(36) NOT NULL,
  `cursor` JSON NULL,
  `selection` JSON NULL,
  `status` VARCHAR(191) NOT NULL DEFAULT 'ACTIVE',
  `last_seen_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `office_presence_session_id_key` (`session_id`),
  KEY `office_presence_org_id_file_id_status_idx` (`org_id`,`file_id`,`status`),
  KEY `office_presence_user_id_status_idx` (`user_id`,`status`),
  CONSTRAINT `office_presence_org_id_fkey` FOREIGN KEY (`org_id`) REFERENCES `organizations` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `office_presence_file_id_fkey` FOREIGN KEY (`file_id`) REFERENCES `files` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `office_presence_session_id_fkey` FOREIGN KEY (`session_id`) REFERENCES `office_sessions` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `office_presence_user_id_fkey` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

